CREATE TABLE internal_companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,

    name VARCHAR(150) NOT NULL,
    logo_path VARCHAR(500),
    primary_color VARCHAR(7) NOT NULL DEFAULT '#009689',
    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_by BIGINT,
    updated_by BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_internal_companies_name UNIQUE (name),

    CONSTRAINT fk_internal_companies_created_by
        FOREIGN KEY (created_by) REFERENCES users(id),

    CONSTRAINT fk_internal_companies_updated_by
        FOREIGN KEY (updated_by) REFERENCES users(id),

    CONSTRAINT chk_internal_companies_color
        CHECK (primary_color ~ '^#[0-9A-Fa-f]{6}$')
);

